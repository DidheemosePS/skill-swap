// A finished meeting record: joined at the given time and stayed for the given minutes.
const stayed = (userId: string, joinedAt: string, minutes: number): AttendanceRecord => ({
  userId,
  joinedAt,
  leftAt: new Date(Date.parse(joinedAt) + minutes * 60_000).toISOString(),
  durationMinutes: minutes,
})

